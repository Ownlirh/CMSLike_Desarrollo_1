CREATE TABLE public.pagina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta VARCHAR(180) NOT NULL UNIQUE,
    autor_id BIGINT NOT NULL REFERENCES public.usuario(id),
    publicada_id BIGINT
);

CREATE TABLE public.revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagina_id BIGINT NOT NULL REFERENCES public.pagina(id),
    autor_id BIGINT NOT NULL REFERENCES public.usuario(id),
    base_id BIGINT REFERENCES public.revision(id),
    titulo VARCHAR(160) NOT NULL,
    plantilla VARCHAR(20) NOT NULL,
    bloques VARCHAR(64000) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    observacion VARCHAR(500)
);

ALTER TABLE public.pagina ADD CONSTRAINT fk_pagina_publicada
    FOREIGN KEY (publicada_id) REFERENCES public.revision(id);

CREATE TABLE public.permiso_pagina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuario(id),
    pagina_id BIGINT NOT NULL REFERENCES public.pagina(id),
    UNIQUE (usuario_id, pagina_id)
);

CREATE TABLE public.permiso_creacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuario(id),
    prefijo VARCHAR(180) NOT NULL,
    UNIQUE (usuario_id, prefijo)
);

CREATE INDEX idx_revision_pagina ON public.revision(pagina_id);
CREATE INDEX idx_revision_estado ON public.revision(estado);
