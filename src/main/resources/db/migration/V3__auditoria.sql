CREATE TABLE audit.evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES public.usuario(id),
    pagina_id BIGINT REFERENCES public.pagina(id),
    revision_id BIGINT REFERENCES public.revision(id),
    accion VARCHAR(40) NOT NULL,
    detalle VARCHAR(500),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_evento_revision ON audit.evento(revision_id);
